  ck(w('чтобы') + .2, 790, -470, 1.1, .01); ck(w('адвоката') - .06, 815, -465, 1.16, .015);
  sfx('whoosh', w('чтобы') - .08, { dur: .3, soft: true });

  // ---- 4 · "адвоката Сола Гудмана" — the business card and the office ----
