  fullClip('x_sA', TA, { dur: DA, tc: 1826.7, tag: '«ВО ВСЕ ТЯЖКИЕ» · 2×08', bri: 1.9, creep: .02, subs: [[.1, 1.38, 'НЕТ! Я НИ ПРИ ЧЁМ!'], [1.42, 3.0, 'ЭТО ВСЁ ИГНАСИО! ЭТО ОН!', 'ИГНАСИО']] });
