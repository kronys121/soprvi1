  clapper(-250, -400, w('второй') + .22, tClap, [['Во все тяжкие', -326, -68, 86, w('=во') - .15], ['2', -190, 136, 80, w('второй') + .3], ['8', 150, 136, 80, w('сезон') + .1], ['2009', -230, 236, 64, w('сезон') + .35], ['пустыня', 110, 236, 60, w('=все') - .1]]);
